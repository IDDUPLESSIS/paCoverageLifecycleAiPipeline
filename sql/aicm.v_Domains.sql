CREATE   VIEW [aicm].[v_Domains]
AS
WITH S AS (
    -- 1) Materialize only the unique keys you need from the big fact table
    SELECT DISTINCT s.AccountName
    FROM dbo.RAI_SP0 AS s
    WHERE s.AccountName IS NOT NULL
),
J AS (
    -- 2) Join to the lookup using a sargable equality
    SELECT n.Domain
    FROM MASTERDATA.dbo.MSTR_CompanyNameMapping_New AS n
    INNER JOIN S
        ON S.AccountName = n.ParentCompanyName
    WHERE n.Domain IS NOT NULL
)
-- 3) De-dup at the end (smaller set)
SELECT DISTINCT Domain
FROM J;
GO

